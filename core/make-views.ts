import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { categoryViewsSql, REFILL_CATEGORIES } from './src/categories.ts'

// 분류 뷰는 categories.ts 에서 찍어낸다. 이 스크립트가 views.sql 의 생성 구간만
// 갈아끼우고, db 경로를 주면 파일 전체를 그 db 에 적용한다.
//
//   node make-views.ts                # views.sql 만 갱신
//   node make-views.ts ../stars.db    # 갱신 후 db 에 적용

const BEGIN = '-- >>> generated by make-views.ts — 손대지 말 것 (categories.ts 를 고치고 다시 돌린다)'
const END = '-- <<< generated'

const path = join(import.meta.dirname, 'sql/views.sql')
const current = readFileSync(path, 'utf8')
const block = `${BEGIN}\n${categoryViewsSql()}\n${END}`

const start = current.indexOf(BEGIN)
const stop = current.indexOf(END)
const next =
  start === -1 || stop === -1
    ? `${current.trimEnd()}\n\n${block}\n`
    : `${current.slice(0, start)}${block}${current.slice(stop + END.length)}`

writeFileSync(path, next)
console.log(`views.sql 갱신 — 분류 뷰 ${next.length}B`)

const dbPath = process.argv[2]
if (dbPath) {
  // CREATE VIEW IF NOT EXISTS 는 이미 있으면 조용히 지나간다. web 의 쿼리 타입은
  // views.sql 이 아니라 db 에 걸린 뷰에서 추론되므로(reylo), 파일의 뷰를 전부
  // 떨어뜨리고 다시 만들어 db 를 views.sql 과 똑같이 맞춘다. 뒤에 정의된 뷰가
  // 앞의 뷰를 참조할 수 있어 역순으로 떨어뜨린다.
  const db = new DatabaseSync(dbPath)
  const views = [...next.matchAll(/CREATE VIEW IF NOT EXISTS (\w+)/g)].map((m) => m[1])
  for (const v of views.reverse()) {
    db.exec(`DROP VIEW IF EXISTS ${v}`)
  }
  db.exec(next)
  // 규칙이 바뀌었을 수 있으므로 굳힌 표는 매번 통째로 다시 채운다.
  db.exec(REFILL_CATEGORIES)
  const n = (db.prepare('SELECT count(*) AS n FROM repo_category').get() as { n: number }).n
  db.close()
  console.log(`${dbPath} 에 적용 — 분류 ${n}건`)
}
